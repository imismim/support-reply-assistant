async def seed() -> None:
    async with AsyncSessionLocal() as session:
        existing = await session.scalar(select(KBArticle.id).limit(1))
        if existing is not None:
            print("Knowledge base already seeded, skipping.")
            return

        for title, content in ARTICLES:
            session.add(KBArticle(title=title, content=content))
        await session.commit()
    print(f"Seeded {len(ARTICLES)} knowledge base articles.")


if __name__ == "__main__":
    asyncio.run(seed())
